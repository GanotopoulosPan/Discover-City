<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use Illuminate\Support\Facades\Http;
use App\Models\Business;
use Carbon\Carbon;
use Illuminate\Support\Facades\Log;

class AIPlannerController extends Controller
{
    public function generatePlan(Request $request)
    {
        try {
            // 1. Έλεγχος αν ο χρήστης έγραψε κάτι στο textarea
            $request->validate([
                'prompt' => 'required|string|max:1000',
            ]);

            // 2. Παίρνουμε το κλειδί της OpenAI από το .env
            $apiKey = env('OPENAI_API_KEY');
            if (!$apiKey) {
                return response()->json(['error' => 'Δεν βρέθηκε OpenAI API Key στο .env!'], 500);
            }

            // 3. Πρώτα παίρνουμε τον καιρό για τις επόμενες ημέρες στον Βόλο από το Open-Meteo API
            $weatherText = "Δεν υπάρχουν διαθέσιμα δεδομένα καιρού αυτή τη στιγμή.";

            try {
                // Καλούμε το Open-Meteo API για τον Βόλο 
                $weatherResponse = Http::withoutVerifying()->get("https://api.open-meteo.com/v1/forecast", [
                    'latitude' => 39.3621,
                    'longitude' => 22.9423,
                    'daily' => 'weather_code,temperature_2m_max',
                    'timezone' => 'Europe/Athens'
                ]);

                if ($weatherResponse->successful()) {
                    $weatherData = $weatherResponse->json();
                    $daily = $weatherData['daily'] ?? [];
                    
                    // Πίνακας μετάφρασης κωδικών καιρού Open-Meteo στα Ελληνικά
                    $weatherCodes = [
                        0 => 'Καθαρός ουρανός',
                        1 => 'Κυρίως αίθριος', 2 => 'Μερική συννεφιά', 3 => 'Συννεφιά',
                        45 => 'Ομίχλη', 48 => 'Ομίχλη με πάγo',
                        51 => 'Ελαφρύ ψιχάλισμα', 53 => 'Ψιχάλισμα', 55 => 'Έντονο ψιχάλισμα',
                        61 => 'Ασθενής βροχή', 63 => 'Βροχή', 65 => 'Ισχυρή βροχή',
                        71 => 'Ελαφριά χιονόπτωση', 73 => 'Χιονόπτωση', 75 => 'Έντονη χιονόπτωση',
                        77 => 'Χιονόνερο',
                        80 => 'Ξαφνικές μπόρες', 81 => 'Μπόρες', 82 => 'Ισχυρές μπόρες',
                        95 => 'Καταιγίδα', 96 => 'Καταιγίδα με χαλάζι', 99 => 'Ισχυρή καταιγίδα'
                    ];

                    $weatherText = "Πρόβλεψη πραγματικού καιρού για τις επόμενες ημέρες στον Βόλο:\n";
                    
                    // Παίρνουμε τις επόμενες 5 ημέρες αυτόματα
                    for ($i = 0; $i < 5; $i++) {
                        if (isset($daily['time'][$i])) {
                            // Μετατροπή ημερομηνίας σε όνομα ημέρας στα ελληνικά και μετάφραση κωδικού καιρού σε κείμενο
                            $dateName = Carbon::parse($daily['time'][$i])->locale('el')->dayName;
                            $code = $daily['weather_code'][$i];
                            $condition = $weatherCodes[$code] ?? 'Μεταβλητός καιρός';
                            $maxTemp = $daily['temperature_2m_max'][$i];
                            
                            $weatherText .= "- {$dateName}: {$condition}, Μέγιστη θερμοκρασία: {$maxTemp}°C.\n";
                        }
                    }
                }
            } catch (\Exception $e) {
                // Αν αποτύχει ο καιρός, το καταγράφουμε χωρις να κρασάρει ο planner
                Log::error("Open-Meteo API Error: " . $e->getMessage());
            }
            // ---------------------------------------------------

            // 4. Παίρνουμε τα μαγαζιά από τη βάση δεδομένων
            $businesses = Business::select('id', 'name', 'category', 'description', 'amenities', 'lat', 'lon')->get();

            // Φτιάχνουμε το κείμενο με τα μαγαζιά για το OpenAI
            $businessesList = "";
            foreach ($businesses as $index => $business) {
                
                $amenitiesData = $business->amenities;
                if (is_string($amenitiesData)) {
                    $amenitiesData = json_decode($amenitiesData, true);
                }
                
                $amenitiesText = is_array($amenitiesData) 
                    ? implode(', ', $amenitiesData) 
                    : $business->amenities;

                $businessesList .= ($index + 1) . ". ID: {$business->id} | Όνομα: {$business->name} | Κατηγορία: {$business->category} | Περιγραφή: {$business->description} | Παροχές: {$amenitiesText} | Τοποθεσία: {$business->lat}, {$business->lon}\n";
            }

            // 5. Στέλνουμε το αίτημα στο API της OpenAI με ενσωματωμένο τον καιρό
            $response = Http::withoutVerifying()
                ->withToken($apiKey)
                ->timeout(60)
                ->post('https://api.openai.com/v1/chat/completions', [
                    'model' => 'gpt-4o-mini',
                    'messages' => [
                        [
                            'role' => 'system',
                            'content' => "Είσαι ο απόλυτος τοπικός ξεναγός για την πόλη του Βόλου. Πρότεινε ΜΟΝΟ αυτά τα μαγαζιά:\n\n" . $businessesList . "

                            Ανάλογα με το αίτημα του χρήστη, δημιούργησε ένα εξατομικευμένο πλάνο επίσκεψης στην πόλη, 
                            συνδυάζοντας τα μαγαζιά που ταιριάζουν καλύτερα.

                            ΚΡΙΣΙΜΟ - Ο ΠΡΑΓΜΑΤΙΚΟΣ ΚΑΙΡΟΣ ΤΗΣ ΠΟΛΗΣ ΓΙΑ ΤΙΣ ΕΠΟΜΕΝΕΣ ΗΜΕΡΕΣ:
                            " . $weatherText . "

                            ΚΑΝΟΝΑΣ ΚΑΙΡΟΥ (ΑΠΑΡΑΒΑΤΟΣ): Πρέπει να μελετήσεις προσεκτικά την παραπάνω λίστα καιρού.
                             Αν ο χρήστης ζητήσει μια εξωτερική δραστηριότητα ή βόλτα για μια συγκεκριμένη ημέρα και η πρόβλεψη 
                             για αυτή την ημέρα δείχνει βροχή, μπόρες ή καταιγίδα, πρέπει ΥΠΟΧΡΕΩΤΙΚΑ να τον προειδοποιήσεις ευγενικά
                              ότι ο καιρός θα είναι βροχερός. Στη συνέχεια, θα του προτείνεις είτε να αλλάξει ημέρα είτε να επιλέξει 
                              μια εναλλακτική εσωτερική δραστηριότητα/μαγαζί από τη λίστα.Ωστόσο αν ζητάει φαί μην του προτείνεις να 
                              πάει καπου να φαέι κτλπ... Μην του λες ποτέ ότι ο καιρός θα είναι καλός 
                              αν η πρόβλεψή σου δείχνει βροχή!
                              Αν ο χρήστης ζητήσει κάτι για συγκεκριμένη ημέρα, να λάβεις υπόψη σου τον καιρό που προβλέπεται για αυτή την ημέρα και να προσαρμόσεις ανάλογα τις προτάσεις σου. 
                               Αν ο χρήστης ζητήσει κάτι γενικά χωρίς να αναφέρει μέρα, τότε μπορείς να προτείνεις κανονικά, αλλά αν αναφερθεί σε εξωτερική δραστηριότητα ή βόλτα, 
                               να τον ενημερώσεις για τον πιθανό καιρό της ημέρας και να του προτείνεις εναλλακτικές αν ο καιρός φαίνεται κακός.
                               Αν ο χρήστης ζητήσει γενικά κάτι για την πόλη χωρίς να αναφέρει τι ακριβώς θέλει, φτιάξε ένα πλάνο που να περιλαμβάνει μια λογική διαδρομή με συνδυασμό μαγαζιών για φαγητό, καφέ και δραστηριότητες, λαμβάνοντας υπόψη τον καιρό της ημέρας. 
                                Αν ο καιρός φαίνεται καλός, μπορείς να προτείνεις περισσότερες εξωτερικές δραστηριότητες και βόλτες. Αν ο καιρός φαίνεται κακός, τότε προτείνεις περισσότερα εσωτερικά μαγαζιά και δραστηριότητες.
                                Αν δεν έχεις καθόλου πληροφορίες για τον καιρό, τότε να ενημερώσεις τον χρήστη ότι δεν έχεις δεδομένα καιρού αυτή τη στιγμή και να του προτείνεις να ελέγξει τον καιρό πριν βγει έξω, δίνοντας του κάποιες γενικές συμβουλές.

                            Επίσης αν ο χρήστης ζητήσει κάτι για συγκεκριμένη ώρα, να λάβεις υπόψη σου αν είναι πρωί, μεσημέρι, απόγευμα ή βράδυ 
                            και να προτείνεις ανάλογα.
                            Για παράδειγμα αν σου ζητήσει κάτι για την σημερινή μέρα, να λάβεις υπόψην σου την ακριβή ώρα Ελλάδος και να του προτείνεις ανάλογα:πχ αν είναι μεσημέρι μην προτείνεις πρωινό κλπ.
                            Τέλος συνδύασε τα μαγαζιά με βάση την τοποθεσία τους, ώστε να φτιάξεις ένα λογικό πλάνο διαδρομής για τον χρήστη,
                             ξεκινώντας από το πιο κοντινό μαγαζί που ταιριάζει με την πρώτη του επιθυμία.
                            
                            ΚΑΝΟΝΑΣ ΓΙΑ ΤΑ ΜΑΓΑΖΙΑ (ΚΡΙΣΙΜΟ): Όταν αναφέρεις οποιοδήποτε μαγαζί από την παραπάνω λίστα,
                             ΜΗΝ το βάζεις απλά με αστεράκια. Πρέπει ΥΠΟΧΡΕΩΤΙΚΑ να το γράφεις ακριβώς σε αυτή τη μορφή,
                              χρησιμοποιώντας το ID του: [shop id=\"Το_ID_Του_Μαγαζιού\"]Όνομα Μαγαζιού[/shop]. 
                            Για παράδειγμα, αν προτείνεις το Crepe Twist που έχει ID 2, θα το γράψεις: [shop id=\"2\"]Crepe Twist[/shop]. 
                            Μην βάζεις αστεράκια (**) γύρω από αυτό το tag, θα γίνει αυτόματα έντονο και clickable.

                            Τέλος να θυμάσαι ότι πρέπει να προτείνεις ΜΟΝΟ μαγαζιά από τη λίστα που σου έδωσα. Αν δεν ταιριάζει κανένα, απλά πες στον χρήστη ότι δεν υπάρχει κάτι που να ταιριάζει με αυτό που ζητάει.
                            Μην γράφεις στον χρήστη σαν να είσαι ΑΙ. Να γράφεις επίσημα και με σεβασμό, σαν να είσαι ένας τοπικός ξεναγός με βαθιά γνώση της πόλης και των μαγαζιών της."
                        ],
                        [
                            'role' => 'user',
                            'content' => $request->input('prompt')
                        ]
                    ],
                    'temperature' => 0.7,
                ]);

            if ($response->successful()) {
                $aiText = $response->json()['choices'][0]['message']['content'];
                return response()->json(['plan' => $aiText]);
            }

            return response()->json(['error' => 'Το OpenAI error: ' . $response->body()], 500);

        } catch (\Exception $e) {
            return response()->json(['error' => $e->getMessage()], 500);
        }
    }
}